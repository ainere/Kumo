/**
 * sync.js — Writes Kumo's provider configuration into a project workspace.
 *
 * Supports Codex (.codex/config.toml and .codex/agents/reviewer.toml) and
 * Antigravity (.agents/mcp_config.json).
 *
 * Nothing here runs implicitly against an arbitrary directory. The rules:
 *   - A workspace is only written to when it is named explicitly; there is no
 *     `process.cwd()` default, because running `kumo config set` from the home
 *     directory used to rewrite the *global* `~/.codex/config.toml`.
 *   - Full synchronization is opt-in: `kumo init` performs it, and afterwards a
 *     session refreshes only workspaces that already carry Kumo-managed files
 *     (`onlyIfManaged`).
 *   - A file Kumo did not create is never overwritten, and the managed TOML
 *     block never redefines a key the user already set (duplicate keys make the
 *     whole file invalid TOML, and Codex then refuses to start).
 *
 * The MCP bridge server is always resolved from *this* Kumo installation, never
 * from the target workspace — the workspace being synchronized is almost never
 * the Kumo repository itself.
 */

import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { detectProviderForModel } from "./settings.js";
import { configFile, atomicWriteText, atomicWriteJson } from "./paths.js";
import { nodeCommand } from "../core/node-command.js";

/** A TOML inline table of string values: `{ A = "1", B = "x" }`. */
function tomlInlineTable(values) {
  return `{ ${Object.entries(values).map(([k, v]) => `${k} = ${JSON.stringify(String(v))}`).join(", ")} }`;
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Absolute path to the bridge server shipped with this Kumo installation. */
export const BRIDGE_SERVER_PATH = path.resolve(__dirname, "../bridge/server.js");

const TOML_BEGIN = "# >>> kumo managed block >>>";
const TOML_END = "# <<< kumo managed block <<<";
const LEGACY_TOML_HEADER = "# Kumo Cross-Provider Orchestrator Configuration";

/** First line of every reviewer.toml Kumo writes; anything else is the user's. */
export const REVIEWER_MARKER = "# kumo-managed: regenerated by Kumo; delete this line to keep your own edits";
/** Phrase that identifies reviewer.toml files written before the marker existed. */
const LEGACY_REVIEWER_SIGNATURE = "genuine cross-model review independence";

function readStoredConfig() {
  try {
    const file = configFile();
    if (fs.existsSync(file)) {
      return JSON.parse(fs.readFileSync(file, "utf-8"));
    }
  } catch {
    /* ignore */
  }
  return {};
}

function readText(p) {
  try {
    return fs.existsSync(p) ? fs.readFileSync(p, "utf-8") : null;
  } catch {
    return null;
  }
}

/**
 * Serialize a value for interpolation into a TOML basic string.
 * Throws on characters that would break out of the string — callers validate
 * these values upstream, so a hit here is a bug, not user error.
 *
 * @param {*} v
 * @returns {string}
 */
export function tomlString(v) {
  const s = String(v ?? "");
  if (/["\r\n\\]/.test(s)) {
    throw new Error(`Value cannot be serialized into TOML: ${JSON.stringify(s)}`);
  }
  return s;
}

/**
 * Write a text file atomically (tmp + rename), using the process umask.
 *
 * @param {string} p
 * @param {string} content
 */
function writeFileAtomic(p, content) {
  atomicWriteText(p, content, undefined);
}

/**
 * Write a JSON file, merging top-level `mcpServers` with any existing file.
 * Missing/corrupt existing JSON is treated as `{}`.
 *
 * @param {string} p
 * @param {object} obj
 */
function writeJsonMerged(p, obj) {
  let old = {};
  if (fs.existsSync(p)) {
    try {
      const raw = fs.readFileSync(p, "utf-8").trim();
      old = raw ? JSON.parse(raw) : {};
      if (!old || typeof old !== "object") old = {};
    } catch {
      old = {};
    }
  }
  const merged = { ...old, ...obj };
  merged.mcpServers = { ...(old.mcpServers || {}), ...(obj.mcpServers || {}) };
  atomicWriteJson(p, merged, undefined);
}

/**
 * Split a TOML document into the parts outside Kumo's managed block.
 *
 * @param {string} text
 * @returns {string}
 */
function outsideManagedBlock(text) {
  const start = text.indexOf(TOML_BEGIN);
  const end = text.indexOf(TOML_END);
  if (start !== -1 && end !== -1 && end > start) {
    return text.slice(0, start) + text.slice(end + TOML_END.length);
  }
  if (text.trimStart().startsWith(LEGACY_TOML_HEADER)) return "";
  return text;
}

/**
 * Which keys and tables a TOML document defines, as far as the managed block
 * can collide with them: root-level keys (dotted or not) that appear before the
 * first table header, and every table header.
 *
 * This is not a TOML parser; it only has to recognize the lines that would
 * conflict with the handful of keys Kumo writes.
 *
 * @param {string} text
 * @returns {{ rootKeys: Set<string>, tables: Set<string> }}
 */
export function definedTomlNames(text) {
  const rootKeys = new Set();
  const tables = new Set();
  let inRoot = true;
  // Lines inside a multi-line value are not keys or headers: an array element
  // such as `["a", "b"],` looks exactly like a table header.
  let openString = null; // '"""' or "'''" while inside a multi-line string
  let arrayDepth = 0;
  const count = (s, ch) => s.split(ch).length - 1;
  const withoutStrings = (s) => s.replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, '""');

  for (const raw of String(text || "").split(/\r?\n/)) {
    const line = raw.trim();
    if (openString) {
      if (line.includes(openString)) openString = null;
      continue;
    }
    if (arrayDepth > 0) {
      const bare = withoutStrings(line.replace(/#.*$/, ""));
      arrayDepth += count(bare, "[") - count(bare, "]");
      continue;
    }
    if (!line || line.startsWith("#")) continue;
    const header = line.match(/^\[\[?\s*([^\]]+?)\s*\]\]?/);
    if (header) {
      inRoot = false;
      tables.add(header[1].replace(/\s+/g, "").replace(/"/g, ""));
      continue;
    }
    const key = line.match(/^([A-Za-z0-9_."-]+)\s*=\s*(.*)$/);
    if (!key) continue;
    if (inRoot) rootKeys.add(key[1].replace(/"/g, ""));

    const value = key[2];
    for (const delim of ['"""', "'''"]) {
      if (count(value, delim) % 2 === 1) openString = delim;
    }
    if (!openString) {
      const bare = withoutStrings(value.replace(/#.*$/, ""));
      arrayDepth = Math.max(0, count(bare, "[") - count(bare, "]"));
    }
  }
  return { rootKeys, tables };
}

/**
 * Whether the managed block may define `key` (a dotted root-level key) given
 * what the user's own TOML already defines.
 *
 * @param {string} key
 * @param {{ rootKeys: Set<string>, tables: Set<string> }} names
 */
function canDefine(key, names) {
  // Taken as a value, or already a table (`[mcp_servers.kumo-bridge.env]`).
  if (names.rootKeys.has(key) || names.tables.has(key)) return false;
  const parts = key.split(".");
  for (let i = 1; i < parts.length; i++) {
    const prefix = parts.slice(0, i).join(".");
    // A table that already exists by header — or a scalar at that path —
    // cannot also be extended with dotted keys from the root.
    if (names.tables.has(prefix) || names.rootKeys.has(prefix)) return false;
  }
  return true;
}

/**
 * Write Kumo's settings into a delimited managed region of a TOML file,
 * preserving every other line the user authored.
 *
 * The block contains only key/value pairs (dotted keys, no `[table]` headers),
 * so it must appear before any table header in the file — TOML scopes bare keys
 * to the most recent table. New blocks are therefore prepended, not appended.
 *
 * `entries` is a list of `[dottedKey, tomlValueLiteral]`; entries the user's
 * part of the file already defines are left out.
 *
 * @param {string} p
 * @param {string} header - comment lines placed at the top of the block
 * @param {Array<[string, string]>} entries
 * @returns {string[]} the keys that were skipped because the user defines them
 */
export function writeTomlManagedBlock(p, header, entries) {
  const existing = readText(p);
  const names = definedTomlNames(existing === null ? "" : outsideManagedBlock(existing));
  const skipped = [];
  const body = [];
  for (const [key, value] of entries) {
    if (canDefine(key, names)) body.push(`${key} = ${value}`);
    else skipped.push(key);
  }
  const wrapped = `${TOML_BEGIN}\n${header.trim()}\n\n${body.join("\n")}\n${TOML_END}\n`;

  if (existing === null) {
    writeFileAtomic(p, wrapped);
    return skipped;
  }

  const start = existing.indexOf(TOML_BEGIN);
  const end = existing.indexOf(TOML_END);
  if (start !== -1 && end !== -1 && end > start) {
    const tail = existing.slice(end + TOML_END.length).replace(/^\r?\n/, "");
    writeFileAtomic(p, existing.slice(0, start) + wrapped + tail);
    return skipped;
  }

  if (existing.trimStart().startsWith(LEGACY_TOML_HEADER)) {
    // Pre-sentinel file generated wholly by Kumo; nothing user-authored to keep.
    writeFileAtomic(p, wrapped);
    return skipped;
  }

  writeFileAtomic(p, `${wrapped}\n${existing.replace(/^\r?\n/, "")}`);
  return skipped;
}

/**
 * True when `reviewer.toml` content was generated by Kumo.
 *
 * @param {string|null} text
 */
function isKumoReviewer(text) {
  return text !== null && (text.startsWith(REVIEWER_MARKER) || text.includes(LEGACY_REVIEWER_SIGNATURE));
}

/**
 * Whether a workspace already carries Kumo-managed provider files — the signal
 * that its owner opted in (via `kumo init`) to having them kept current.
 *
 * @param {string} workspaceDir
 * @returns {boolean}
 */
export function hasManagedConfigs(workspaceDir) {
  if (!workspaceDir) return false;
  const toml = readText(path.join(workspaceDir, ".codex", "config.toml"));
  if (toml && (toml.includes(TOML_BEGIN) || toml.trimStart().startsWith(LEGACY_TOML_HEADER))) return true;
  return isKumoReviewer(readText(path.join(workspaceDir, ".codex", "agents", "reviewer.toml")));
}

/**
 * Make sure Antigravity can reach the bridge from `workspaceDir`.
 *
 * Antigravity has no command-line flag for MCP servers; it reads them from
 * `.agents/mcp_config.json` in the workspace. Only the `kumo-bridge` entry is
 * merged in — every other server the file lists is preserved.
 *
 * @param {string} workspaceDir
 * @returns {boolean} true when the file was created or changed
 */
export function ensureAntigravityBridgeConfig(workspaceDir) {
  if (!workspaceDir || process.env.KUMO_NO_SYNC === "1") return false;
  const file = path.join(workspaceDir, ".agents", "mcp_config.json");
  // The file stays in the workspace and the CLI reads it too: a real node,
  // not the desktop app's Electron binary (see node-command.js).
  const node = nodeCommand({ persistent: true });
  const entry = {
    command: node.command,
    args: [BRIDGE_SERVER_PATH],
    env: { ...node.env, KUMO_WORKSPACE: workspaceDir },
  };
  try {
    const current = JSON.parse(readText(file) || "{}");
    if (JSON.stringify(current?.mcpServers?.["kumo-bridge"]) === JSON.stringify(entry)) return false;
  } catch {
    /* rewrite below */
  }
  try {
    writeJsonMerged(file, { mcpServers: { "kumo-bridge": entry } });
    return true;
  } catch {
    return false;
  }
}

/**
 * Synchronize orchestrator and worker settings into a workspace's provider files.
 *
 * @param {string} workspaceDir - required; never defaults to the process cwd
 * @param {Object} [customConfig] - Optional loaded config object
 * @param {{ onlyIfManaged?: boolean }} [options] - skip workspaces that have no
 *   Kumo-managed files yet (sessions refresh; only `kumo init` creates them)
 * @returns {{ written: string[], skipped: string[] }}
 */
export function syncAgentConfigs(workspaceDir, customConfig = null, options = {}) {
  const report = { written: [], skipped: [] };
  if (process.env.KUMO_NO_SYNC === "1" || !workspaceDir) return report;
  if (options.onlyIfManaged && !hasManagedConfigs(workspaceDir)) return report;

  try {
    const persistentNode = nodeCommand({ persistent: true });
    const config = customConfig || readStoredConfig();
    const orchModel = tomlString(config.orchestratorModel || "chatgpt-6-astra");
    const orchEffort = tomlString(config.reasoningEffort || "low");
    const orchProvider = tomlString(config.orchestratorProvider || detectProviderForModel(orchModel));

    const workerModel = tomlString(config.workerModel || "gemini-3.8-flash");
    const workerEffort = tomlString(config.workerEffort || "medium");
    const workerProvider = tomlString(config.workerProvider || detectProviderForModel(workerModel));
    const approvalPolicy = tomlString(config.approvalPolicy || "on-request");

    const isAntigravity = (p) => p === "antigravity" || p === "gemini" || p === "agy";

    // 1. Codex (.codex/agents/reviewer.toml & .codex/config.toml)
    const codexDir = path.join(workspaceDir, ".codex");
    const agentsDir = path.join(codexDir, "agents");

    if (fs.existsSync(codexDir) || orchProvider === "codex" || workerProvider === "codex") {
      const reviewerPath = path.join(agentsDir, "reviewer.toml");
      const existingReviewer = readText(reviewerPath);
      if (existingReviewer !== null && !isKumoReviewer(existingReviewer)) {
        report.skipped.push(reviewerPath);
      } else {
        fs.mkdirSync(agentsDir, { recursive: true });
        writeFileAtomic(reviewerPath, reviewerToml({ orchModel, orchEffort, workerModel, workerEffort }));
        report.written.push(reviewerPath);
      }

      const configTomlPath = path.join(codexDir, "config.toml");
      const header = `${LEGACY_TOML_HEADER}
# Automatically synchronized with active user settings.
# Everything between the kumo sentinels is regenerated; edit outside the block.
# Keys you define outside the block always win; Kumo leaves them out of it.
# Active Orchestrator: ${orchModel} (${orchEffort}) [${orchProvider}]
# Active Worker:       ${workerModel} (${workerEffort}) [${workerProvider}]`;
      const skippedKeys = writeTomlManagedBlock(configTomlPath, header, [
        ["model", `"${orchModel}"`],
        ["model_reasoning_effort", `"${orchEffort}"`],
        ["approval_policy", `"${approvalPolicy}"`],
        ["agents.enabled", "true"],
        ["agents.max_concurrent_threads_per_session", "4"],
        ["mcp_servers.kumo-bridge.command", JSON.stringify(persistentNode.command)],
        ["mcp_servers.kumo-bridge.args", `[${JSON.stringify(BRIDGE_SERVER_PATH)}]`],
        ["mcp_servers.kumo-bridge.env", tomlInlineTable({ ...persistentNode.env, KUMO_WORKSPACE: workspaceDir })],
      ]);
      report.written.push(configTomlPath);
      for (const key of skippedKeys) report.skipped.push(`${configTomlPath}:${key}`);
    }

    // 2. Antigravity (.agents/mcp_config.json, and the opt-in global Gemini file)
    if (
      fs.existsSync(path.join(workspaceDir, ".agents")) ||
      isAntigravity(orchProvider) ||
      isAntigravity(workerProvider)
    ) {
      ensureAntigravityBridgeConfig(workspaceDir);
      report.written.push(path.join(workspaceDir, ".agents", "mcp_config.json"));

      // Global gemini sync is opt-in (avoids leaking workspace paths on every save)
      if (process.env.KUMO_SYNC_GLOBAL_GEMINI === "1") {
        try {
          const geminiGlobalDir = path.join(os.homedir(), ".gemini", "config");
          if (fs.existsSync(geminiGlobalDir)) {
            writeJsonMerged(path.join(geminiGlobalDir, "mcp_config.json"), {
              mcpServers: {
                "kumo-bridge": {
                  command: persistentNode.command,
                  args: [BRIDGE_SERVER_PATH],
                  ...(Object.keys(persistentNode.env).length > 0 ? { env: persistentNode.env } : {}),
                  disabled: false,
                },
              },
            });
          }
        } catch {
          /* ignore */
        }
      }
    }
  } catch {
    // Non-fatal if workspace is read-only or not yet initialized
  }
  return report;
}

function reviewerToml({ orchModel, orchEffort, workerModel, workerEffort }) {
  return `${REVIEWER_MARKER}
name = "reviewer"
description = "Independent code reviewer. Uses the active orchestrator model to review code written by the execution worker for genuine cross-model review independence."

model = "${orchModel}"
model_reasoning_effort = "${orchEffort}"
sandbox_mode = "read-only"

developer_instructions = """
You are an independent code review subagent representing the Orchestrator (running on ${orchModel} with ${orchEffort} reasoning effort).

IMPORTANT: The code you are reviewing was written by the execution worker (running on ${workerModel} with ${workerEffort} reasoning effort).
Because you and the worker run on distinct models and contexts, you provide genuine cross-model independence to catch blind spots, regressions, and contract violations.

Review the actual change, not the intended story.

Prioritize:
- Correctness bugs
- Behavior regressions
- Security and permission issues
- Data loss or integrity risks
- Race/concurrency problems
- API or compatibility breaks
- Missing high-value tests

Rules:
- Avoid style-only comments unless they hide a real defect
- Do not edit files

For each finding include:
- Severity (Critical, Warning, Info)
- Exact file/symbol/line
- Why it is a problem
- A concrete fix or validation step

If there are no material findings, say so clearly and name any residual uncertainty.
"""
`;
}
