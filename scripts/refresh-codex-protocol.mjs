#!/usr/bin/env node
/**
 * refresh-codex-protocol.mjs — Regenerate the vendored Codex app-server types.
 *
 * Runs `codex app-server generate-ts` from the installed Codex CLI and copies
 * the type files Kumo uses — the roots below plus everything they import —
 * into src/core/vendor/codex-protocol/. The full output is ~700 files; Kumo
 * needs about 150 of them.
 *
 *   node scripts/refresh-codex-protocol.mjs
 *
 * Re-run after upgrading Codex, then run `npm run typecheck` and the tests.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { findCodexBinary } from "../src/providers/orchestrators/codex.js";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dest = path.join(repo, "src", "core", "vendor", "codex-protocol");

/** The protocol messages Kumo sends or reads (see codex-client.js). */
const ROOTS = [
  "ServerRequest",
  "v2/ThreadStartParams",
  "v2/ThreadStartResponse",
  "v2/ThreadResumeParams",
  "v2/ThreadResumeResponse",
  "v2/TurnStartParams",
  "v2/TurnStartResponse",
  "v2/TurnInterruptParams",
  "v2/ItemStartedNotification",
  "v2/ItemCompletedNotification",
  "v2/TurnCompletedNotification",
  "v2/AgentMessageDeltaNotification",
  "v2/ReasoningTextDeltaNotification",
  "v2/ReasoningSummaryTextDeltaNotification",
  "v2/ErrorNotification",
  "v2/McpServerStatusUpdatedNotification",
  "v2/ModelListParams",
  "v2/ModelListResponse",
  "v2/GetAccountRateLimitsResponse",
];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "kumo-codex-ts-"));
try {
  const bin = findCodexBinary();
  const version = execFileSync(bin, ["--version"], { encoding: "utf-8" }).trim();
  execFileSync(bin, ["app-server", "generate-ts", "--out", tmp], { stdio: "inherit" });

  const seen = new Set();
  const queue = [...ROOTS];
  while (queue.length > 0) {
    const rel = queue.shift();
    if (seen.has(rel)) continue;
    const file = path.join(tmp, `${rel}.ts`);
    if (!fs.existsSync(file)) throw new Error(`generate-ts produced no ${rel}.ts — has the protocol changed?`);
    seen.add(rel);
    const source = fs.readFileSync(file, "utf-8");
    for (const match of source.matchAll(/from "(\.[^"]+)"/g)) {
      queue.push(path.posix.normalize(path.posix.join(path.posix.dirname(rel), match[1])));
    }
  }

  fs.rmSync(dest, { recursive: true, force: true });
  for (const rel of [...seen].sort()) {
    const target = path.join(dest, `${rel}.ts`);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.copyFileSync(path.join(tmp, `${rel}.ts`), target);
  }
  fs.writeFileSync(
    path.join(dest, "README.md"),
    `# Vendored Codex app-server types\n\n` +
      `Generated by \`node scripts/refresh-codex-protocol.mjs\` from ${version} ` +
      `(\`codex app-server generate-ts\`). Do not edit; re-run the script after upgrading Codex.\n\n` +
      `Roots: ${ROOTS.map((r) => `\`${r}\``).join(", ")}, and every type they import (${seen.size} files).\n`
  );
  console.log(`Vendored ${seen.size} files from ${version} into ${path.relative(repo, dest)}`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
