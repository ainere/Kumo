/** A placeholder other than `last`, when there's another to give. */
export function randomPlaceholder(last?: string): string {
  const pool = PLACEHOLDERS.length > 1 ? PLACEHOLDERS.filter((line) => line !== last) : PLACEHOLDERS;
  return pool[Math.floor(Math.random() * pool.length)];
}
